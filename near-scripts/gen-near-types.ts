/**
 * Generates app/near/generated/*.ts from the contracts' `cargo near abi`
 * output (app/near/abi/*.json, copied from the contracts repo's near/abi/).
 *
 *   npx tsx near-scripts/gen-near-types.ts
 *
 * Each ABI becomes: one TS type per schema definition, plus `Views` and
 * `Calls` maps (method name -> { args, result }) that app/near/useNearView
 * and useNearCall are typed against. Regenerate whenever the contracts
 * agent publishes a new ABI, then let `tsc` show what broke.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
type Schema = Record<string, unknown>;

interface AbiFunction {
  name: string;
  kind: "view" | "call";
  modifiers?: string[];
  params?: { serialization_type: string; args: { name: string; type_schema: Schema }[] };
  result?: { serialization_type: string; type_schema: Schema };
}

interface Abi {
  body: { functions: AbiFunction[]; root_schema: { definitions?: Record<string, Schema> } };
}

const ROOT = join(__dirname, "..");

/** Methods no player-facing or admin UI should ever call. */
const SKIP = new Set(["new", "migrate", "upgrade", "upgrade_probe", "resolve_randomness", "nft_resolve_transfer"]);

/** Inline schema -> TS type expression; named definitions by reference. */
function tsType(s: Schema | boolean | undefined): string {
  if (s === true || s === undefined) return "unknown";
  if (s === false) return "never";
  if (typeof s.$ref === "string") {
    const name = s.$ref.split("/").pop()!;
    return name === "Promise" ? "unknown" : name;
  }
  const anyOf = (s.anyOf ?? s.oneOf) as Schema[] | undefined;
  if (anyOf) return anyOf.map(tsType).join(" | ");
  const allOf = s.allOf as Schema[] | undefined;
  if (allOf) return allOf.map(tsType).join(" & ");
  if (Array.isArray(s.enum)) return (s.enum as unknown[]).map((v) => JSON.stringify(v)).join(" | ");
  const type = s.type;
  if (Array.isArray(type)) return type.map((t) => tsType({ ...s, type: t } as Schema)).join(" | ");
  switch (type) {
    case "null":
      return "null";
    case "boolean":
      return "boolean";
    case "string":
      return "string";
    case "integer":
    case "number":
      return "number";
    case "array": {
      const items = s.items as Schema | Schema[] | undefined;
      if (Array.isArray(items)) return `[${items.map(tsType).join(", ")}]`;
      return `Array<${tsType(items)}>`;
    }
    case "object": {
      const props = s.properties as Record<string, Schema> | undefined;
      if (props) {
        const req = new Set((s.required as string[] | undefined) ?? []);
        return `{ ${Object.entries(props)
          .map(([k, v]) => `${k}${req.has(k) ? "" : "?"}: ${tsType(v)}`)
          .join("; ")} }`;
      }
      const add = s.additionalProperties as Schema | boolean | undefined;
      return `Record<string, ${tsType(add)}>`;
    }
    default:
      return "unknown";
  }
}

async function generate(abiFile: string, outFile: string, label: string) {
  const abi = JSON.parse(readFileSync(join(ROOT, "app/near/abi", abiFile), "utf8")) as Abi;
  const defs = abi.body.root_schema.definitions ?? {};

  const types = Object.entries(defs)
    // near-sdk's "Promise" result schema would shadow the global Promise type.
    .filter(([name]) => name !== "Promise")
    .map(([name, def]) => {
      const doc = typeof def.description === "string" ? `/** ${def.description.replace(/\*\//g, "* /")} */\n` : "";
      return `${doc}export type ${name} = ${tsType(def)};`;
    })
    .join("\n\n");

  const views: string[] = [];
  const calls: string[] = [];
  const payable: string[] = [];
  for (const f of abi.body.functions) {
    if (SKIP.has(f.name) || f.modifiers?.includes("private")) continue;
    const args = f.params?.args ?? [];
    const argsType = args.length
      ? `{ ${args.map((a) => `${a.name}: ${tsType(a.type_schema)}`).join("; ")} }`
      : "Record<string, never>";
    const resultType = f.result ? tsType(f.result.type_schema) : "void";
    const line = `  ${f.name}: { args: ${argsType}; result: ${resultType} };`;
    if (f.kind === "view") views.push(line);
    else {
      calls.push(line);
      if (f.modifiers?.includes("payable")) payable.push(JSON.stringify(f.name));
    }
  }

  const out = `// GENERATED by near-scripts/gen-near-types.ts from app/near/abi/${abiFile}.
// Do not edit by hand: copy the new ABI from the contracts repo
// (near/abi/) and rerun \`npx tsx near-scripts/gen-near-types.ts\`.
//
// u64 ids inside structs arrive as JSON numbers (raw u64); U64/U128 values
// (token amounts, ids in arguments/returns) are decimal strings.

${types.trim()}

/** ${label} view methods: name -> { args, result }. */
export interface Views {
${views.join("\n")}
}

/** ${label} call (change) methods: name -> { args, result }. */
export interface Calls {
${calls.join("\n")}
}

/** Calls that accept an attached deposit. */
export const PAYABLE_METHODS = [${payable.join(", ")}] as const;
`;
  writeFileSync(join(ROOT, "app/near/generated", outFile), out);
  console.log(`wrote app/near/generated/${outFile}: ${views.length} views, ${calls.length} calls`);
}

async function main() {
  await generate("void_tactics_abi.json", "voidTactics.ts", "Game contract");
  await generate("void_renderer_abi.json", "voidRenderer.ts", "Renderer contract");
}

void main();
