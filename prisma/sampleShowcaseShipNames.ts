import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import rawNames from "../app/lib/shipNames.json";

// Writes app/data/content/showcaseShipNames.ts: a random sample of the
// consortium ship names (app/lib/shipNames.json, ~336 KB) for the website's
// decorative ships (generateRandomShip), so the full list never ships to the
// browser. Re-run when the full list changes:
//
//   npx tsx prisma/sampleShowcaseShipNames.ts

const SAMPLE_SIZE = 300;

const names = [...new Set((rawNames as string[]).map((n) => n.trim()).filter(Boolean))];
for (let i = names.length - 1; i > 0; i--) {
  const j = Math.floor(Math.random() * (i + 1));
  [names[i], names[j]] = [names[j], names[i]];
}
const sample = names.slice(0, SAMPLE_SIZE).sort((a, b) => a.localeCompare(b));

const out = `// Generated by prisma/sampleShowcaseShipNames.ts: ${sample.length} of the
// ${names.length} consortium ship names in app/lib/shipNames.json, for the
// website's decorative ships. Re-run the script instead of editing by hand.
export const SHOWCASE_SHIP_NAMES: readonly string[] = ${JSON.stringify(sample, null, 2)};
`;
const path = resolve(__dirname, "../app/data/content/showcaseShipNames.ts");
writeFileSync(path, out);
console.log(`Wrote ${sample.length} names to ${path}`);
